#!/usr/bin/env node
/**
 * Generate cordis.patch.yml from the DSH installation's shipped `standard`
 * preset.
 *
 * Why generate instead of hand-writing: a preset's `plugins` list is the
 * COMPLETE child composition, not an overlay — presets do not inherit. So an
 * `opensocrates` preset must restate the full tool surface. Copying that list
 * by hand would silently rot; this script re-derives it from the installed
 * DSH so the diff is reviewable and regeneration is one command.
 *
 * The plugin subtree is reused VERBATIM as text so `!!js` expressions and
 * comments survive exactly as shipped.
 *
 * Usage:
 *   node tools/gen-preset.mjs [--standard <path to standard.patch.yml>] [--check]
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

const PRESET_ID = 'opensocrates';
const ROW_ID = 'preset-opensocrates';
const DISPLAY_NAME = 'OpenSocrates';
const DISPLAY_DESC =
  'Reasoning method pack — 48 authored methods (zh), applied on judgment tasks.';

/** Emit a YAML plain scalar safely (quote when it could be misparsed). */
function yamlScalar(value) {
  if (/^[A-Za-z0-9][A-Za-z0-9 _.,()/-]*$/.test(value) && !/:\s|:$/.test(value)) return value;
  return `'${value.replace(/'/g, "''")}'`;
}

/** Locate the shipped standard preset inside a DSH installation. */
function findStandard(explicit) {
  if (explicit) {
    if (!existsSync(explicit)) throw new Error(`--standard not found: ${explicit}`);
    return explicit;
  }
  const roots = [
    process.env.DSH_CHECKOUT,
    '/home/joey/.local/share/pnpm/global/v11/582d3-1a13061ff6b',
    join(process.env.DSH_HOME ?? '', '..'),
  ].filter(Boolean);

  for (const root of roots) {
    const direct = join(root, 'node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml');
    if (existsSync(direct)) return direct;
    // versioned global layout: <root>/v11/<hash>/node_modules/...
    const v11 = join(root, 'v11');
    if (existsSync(v11)) {
      for (const hash of readdirSync(v11)) {
        const p = join(v11, hash, 'node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml');
        if (existsSync(p)) return p;
      }
    }
  }
  throw new Error('could not locate standard.patch.yml; pass --standard <path>');
}

/** Extract the lines under `plugins:` (the child entry list), verbatim. */
function extractPlugins(text, source) {
  const lines = text.split('\n');
  const idx = lines.findIndex((l) => /^\s*plugins:\s*$/.test(l));
  if (idx === -1) throw new Error(`no 'plugins:' key in ${source}`);
  const indent = lines[idx].match(/^\s*/)[0].length;
  const out = [];
  for (let i = idx + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === '') {
      out.push(line);
      continue;
    }
    const cur = line.match(/^\s*/)[0].length;
    if (cur <= indent) break;
    out.push(line);
  }
  while (out.length && out[out.length - 1].trim() === '') out.pop();
  return { indent, body: out };
}

const argv = process.argv.slice(2);
const standardArg = argv.includes('--standard') ? argv[argv.indexOf('--standard') + 1] : undefined;
const checkOnly = argv.includes('--check');

const standardPath = findStandard(standardArg);
const standardText = readFileSync(standardPath, 'utf8');
const { body } = extractPlugins(standardText, standardPath);

// Append our row at the same nesting level as the shipped plugin rows.
const sampleRow = body.find((l) => /^\s*-\s+id:/.test(l));
if (!sampleRow) throw new Error('could not determine plugin row indentation');
const rowIndent = sampleRow.match(/^\s*/)[0];

const ourRow = [
  `${rowIndent}- id: opensocrates-method-pack`,
  `${rowIndent}  name: 'dsh-opensocrates/index.js'`,
];

const presetIndent = '        '; // inside: - insert: / - id: preset-x / config:
const generated = `# GENERATED by tools/gen-preset.mjs — do not edit by hand.
# Regenerate: node tools/gen-preset.mjs
#
# Source of the child plugin list: ${standardPath}
#
# A preset's \`plugins\` list is the COMPLETE child composition — presets do not
# inherit, so this file restates the shipped \`standard\` surface plus the
# OpenSocrates skill provider. Regenerating after a DSH upgrade is the intended
# way to pick up new host plugins.
- insert:
    - id: ${ROW_ID}
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: ${PRESET_ID}
        name: ${yamlScalar(DISPLAY_NAME)}
        description: ${yamlScalar(DISPLAY_DESC)}
        order: 20
${presetIndent}plugins:
${[...body, ...ourRow].join('\n')}
`;

const outPath = join(repoRoot, 'cordis.patch.yml');
if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== generated) {
    console.error('DRIFT: cordis.patch.yml differs from regenerated output');
    process.exit(1);
  }
  console.log('OK: cordis.patch.yml matches the installed standard preset');
  process.exit(0);
}
writeFileSync(outPath, generated);
console.log(`wrote ${outPath}`);
console.log(`  source preset : ${standardPath}`);
console.log(`  plugin rows   : ${body.filter((l) => /^\s*-\s+id:/.test(l)).length} (standard) + 1 (opensocrates)`);
